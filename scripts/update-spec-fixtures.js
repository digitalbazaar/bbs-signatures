// Pulls the test fixtures from the IETF CFRG draft repositories and writes
// them, unchanged, as JS modules in `test/fixtures/spec/` (modules rather
// than JSON files so the same tests run under node and karma).
//
// Usage: node scripts/update-spec-fixtures.js
import {writeFile} from 'node:fs/promises';

const SPECS = [{
  name: 'blind',
  title: 'Blind BBS Signatures (draft-irtf-cfrg-bbs-blind-signatures)',
  repo: 'cfrg/draft-irtf-cfrg-bbs-blind-signatures'
}, {
  name: 'pseudonym',
  title: 'BBS per Verifier Linkability (draft-irtf-cfrg-bbs-per-verifier-' +
    'linkability)',
  repo: 'cfrg/draft-irtf-cfrg-bbs-pseudonyms'
}];
const BRANCH = 'main';
const PREFIX = 'fixtures/fixture_data/';

async function getJson(url) {
  const response = await fetch(url, {
    headers: {'user-agent': 'bbs-signatures-update-spec-fixtures'}
  });
  if(!response.ok) {
    throw new Error(`${url}: ${response.status} ${response.statusText}`);
  }
  return response.json();
}

for(const {name, title, repo} of SPECS) {
  const {sha} = await getJson(
    `https://api.github.com/repos/${repo}/commits/${BRANCH}`);
  const {tree} = await getJson(
    `https://api.github.com/repos/${repo}/git/trees/${sha}?recursive=1`);
  // `{suite: {kind: {file: fixture}}}` plus `messages`
  const fixtures = {};
  const files = tree
    .filter(({path, type}) => type === 'blob' && path.startsWith(PREFIX) &&
      path.endsWith('.json'))
    .map(({path}) => path)
    .sort();
  for(const path of files) {
    const data = await getJson(
      `https://raw.githubusercontent.com/${repo}/${sha}/${path}`);
    const parts = path.slice(PREFIX.length).replace(/\.json$/, '').split('/');
    let node = fixtures;
    for(const part of parts.slice(0, -1)) {
      node = node[part] = node[part] ?? {};
    }
    node[parts.at(-1)] = data;
  }
  const out = `/* eslint-disable */
/*!
 * Generated by scripts/update-spec-fixtures.js; do not edit.
 *
 * ${title} test fixtures, unchanged from
 * https://github.com/${repo}/tree/${sha}/${PREFIX}
 */
export const SOURCE = ${JSON.stringify({repo, commit: sha})};
export default ${JSON.stringify(fixtures, null, 2)};
`;
  const target = new URL(`../test/fixtures/spec/${name}.js`, import.meta.url);
  await writeFile(target, out);
  console.log(
    `${name}: ${files.length} files from ${repo}@${sha.slice(0, 12)}`);
}
